inline void colormapper_init_table() {
	for (int i = 0, b = 0; i < 768; i++) {
		unsigned char background = ((i / 3) % 256) >> 4;
		unsigned char foreground = ((i / 3) % 16);
		wchar_t character = L" ░▒"[i % 3];
		if (background == foreground && character != L' ')
			continue;
		if (background != foreground && character == L' ')
			continue;
		
		chco[b].ch = character;
		chco[b++].co = foreground | background << 4;
	}
	
	colormapper_table_init = true;
}

