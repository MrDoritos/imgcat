inline float sampleNormal() {
    float u = ((float) rand() / (RAND_MAX)) * 2 - 1;
    //float v = ((float) rand() / (RAND_MAX)) * 2 - 1;
    //float r = (u * u + v * v) * horizontalScale;
    float v = u * u;
    float r = (v + v) * horizontalScale;

    if (r == 0 || r > 1) 
        return sampleNormal();

    float c = sqrt(-2 * log(r) / r);
    return u * c * verticalScale;
}

